# Print the classic map rects for the zone maps that WoW Forever draws differently.
#
# Sku's database stores spawns, entrances and quest areas as map percentages on the
# CLASSIC zone maps (identical on Era and Anniversary). Forever ships its own
# UiMapAssignment for a few zones (Stormwind, Mulgore, Eastern Plaguelands, Redridge),
# so C_Map.GetWorldPosFromMapPos turns those percentages into the wrong world spot.
# SkuNav/Core.lua (tForeverClassicMapRect) converts them with the classic rect instead.
# This script reads both clients' UiMapAssignment from wago.tools and prints the table
# rows for every zone whose whole-map rect differs. Rerun it after a Forever patch.
#
# Usage:  py -3 _forever_map_rects.py [forever_build] [classic_build]
#   defaults: the newest wow_cn_beta (Forever) and wow_anniversary builds on wago.tools

import csv
import io
import json
import sys
import urllib.request

WAGO = "https://wago.tools"


def fetch(path):
    req = urllib.request.Request(WAGO + path, headers={"User-Agent": "sku-dev"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")


def newest(product):
    return json.loads(fetch("/api/builds"))[product][0]["version"]


def whole_map_rects(build):
    rects = {}
    for r in csv.DictReader(io.StringIO(fetch("/db2/UiMapAssignment/csv?build=" + build))):
        whole = (float(r["UiMin_0"]), float(r["UiMin_1"]), float(r["UiMax_0"]), float(r["UiMax_1"])) == (0, 0, 1, 1)
        if whole and r["OrderIndex"] == "0":
            rects[int(r["UiMapID"])] = tuple(float(r[k]) for k in ("Region_0", "Region_1", "Region_3", "Region_4"))
    return rects


def zone_names(build):
    # Type 3 = zone; continents (2) never carry Sku database percentages
    return {int(r["ID"]): r["Name_lang"] for r in csv.DictReader(io.StringIO(fetch("/db2/UiMap/csv?build=" + build)))
            if r["Type"] == "3"}


forever = sys.argv[1] if len(sys.argv) > 1 else newest("wow_cn_beta")
classic = sys.argv[2] if len(sys.argv) > 2 else newest("wow_anniversary")
fr, cr, names = whole_map_rects(forever), whole_map_rects(classic), zone_names(classic)

print("-- generated by dev/rework-docs/_forever_map_rects.py: Forever %s vs classic %s" % (forever, classic))
for m in sorted(set(fr) & set(cr) & set(names)):
    if max(abs(a - b) for a, b in zip(fr[m], cr[m])) > 0.5:
        print("\t[%d] = {%.3f, %.3f, %.3f, %.3f}, -- %s" % ((m,) + cr[m] + (names[m],)))
