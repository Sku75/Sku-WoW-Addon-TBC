-- Root contributions. Centralised here DELIBERATELY (W6-B #10, resolving the old
-- "trivial follow-up" TODO as won't-do): keeping every root RegisterModule call
-- in one reviewable file beside SetRootLayout means "what is on the root and in
-- what order" stays greppable in a single place. Scattering these into the owning
-- modules buys nothing (builders/labels already resolve their globals lazily at
