-- Root contributions. Centralised here for this first construct (lowest risk,
-- one reviewable file); moving each RegisterModule call into its owning module is
-- a trivial follow-up — the mechanism is identical, since builders resolve their
-- module globals lazily at open time. Labels resolve at open time too, matching
-- the original (which read L[...] inside the open handler).
local function L() return Sku.L end

SkuMenu:RegisterModule("SkuNav",   { label = function() return L()["SkuNavMenuEntry"]   end, build = function(entry) SkuNav:MenuBuilder(entry)   end })
SkuMenu:RegisterModule("SkuMob",   { label = function() return L()["SkuMobMenuEntry"]   end, build = function(entry) SkuMob:MenuBuilder(entry)   end })
SkuMenu:RegisterModule("SkuChat",  { label = function() return L()["SkuChatMenuEntry"]  end, build = function(entry) SkuChat:MenuBuilder(entry)  end })
SkuMenu:RegisterModule("SkuQuest", { label = function() return L()["SkuQuestMenuEntry"] end, build = function(entry) SkuQuest:MenuBuilder(entry) end })
SkuMenu:RegisterModule("SkuCore",  { label = function() return L()["SkuCoreMenuEntry"]  end, build = function(entry) SkuCore:MenuBuilder(entry)  end })
SkuMenu:RegisterModule("SkuAuras", { label = function() return L()["SkuAurasMenuEntry"] end, build = function(entry) SkuAuras:MenuBuilder(entry) end })

-- Game Options: Blizzard's built-in game options (modern Settings system, else
-- only reachable via the Escape menu) made accessible through Sku's menu. Logic
-- in SkuCore/gameOptions.lua. Title is locale-computed at open time, as before.
SkuMenu:RegisterModule("GameOptions", {
	label = function() return (GetLocale and GetLocale() == "deDE") and "Spieloptionen" or "Game Options" end,
	build = function(entry)
		if SkuCore and SkuCore.GameOptionsMenuBuilder then
			SkuCore:GameOptionsMenuBuilder(entry)
		end
	end,
})

-- Default root layout — IDENTICAL order to the old hardcoded sequence.
SkuMenu:SetRootLayout({
	"SkuNav",
	"SkuMob",
	"SkuChat",
	"SkuQuest",
	"SkuCore",
	"SkuAuras",
	"GameOptions",
})
