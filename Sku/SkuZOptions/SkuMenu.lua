-- Register a module's root contribution.
function SkuMenu:RegisterModule(aId, aSpec)
	if type(aId) ~= "string" or type(aSpec) ~= "table" then
		if dprint then dprint("SkuMenu:RegisterModule: bad args", tostring(aId)) end
		return self
	end
	self.registry[aId] = aSpec
	return self
end

-- Set/replace the root layout order (a list of registered ids).
function SkuMenu:SetRootLayout(aIdList)
	self.rootLayout = aIdList or {}
	return self
end

---------------------------------------------------------------------------------------------------------------------------------------
-- Resolve a spec's label (string or function) at assembly time. Falls back to
-- the id so a mis-registered label never produces a nil menu name.
local function resolveLabel(aSpec, aId)
	local lbl = aSpec.label
	if type(lbl) == "function" then
		local ok, r = pcall(lbl)
		if ok and r ~= nil then return r end
		return aId
	end
	if lbl ~= nil then return lbl end
	return aId
end

-- Inject one registered module as a dynamic root entry whose BuildChildren runs
-- the registered builder. Mirrors EXACTLY the old hand-written per-module block
-- (entry.dynamic = true; BuildChildren -> Module:MenuBuilder(entry)). Returns the
-- created entry (or nil for an unregistered id).
function SkuMenu:InjectModuleEntry(aRootMenu, aId)
	local spec = self.registry[aId]
	if not spec then
		if dprint then dprint("SkuMenu:InjectModuleEntry: unregistered id", tostring(aId)) end
		return nil
	end
	local tEntry = SkuOptions:InjectMenuItems(aRootMenu, {resolveLabel(spec, aId)}, SkuGenericMenuItem)
	tEntry.dynamic = true
	if spec.sorting then
		tEntry.sorting = true
	end
	local buildFn = spec.build
	tEntry.BuildChildren = function(self)
		if buildFn then
			buildFn(self)
		end
	end
	return tEntry
end

-- Assemble the registered root entries, in layout order, into aRootMenu.
-- Injecting one at a time into the same parent reproduces the original prev/next
-- sibling chain exactly (InjectMenuItems links each new item to the previous).
function SkuMenu:AssembleRoot(aRootMenu)
	for i = 1, #self.rootLayout do
		self:InjectModuleEntry(aRootMenu, self.rootLayout[i])
	end
	return self
end

